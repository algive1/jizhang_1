test('会员管理：鉴权、套餐启停、权益覆盖、用户调整、到期和审计保持一致',async t=>{
  const previous={ADMIN_TOKEN:process.env.ADMIN_TOKEN,ALL_FEATURES_FREE_FOR_TESTING:process.env.ALL_FEATURES_FREE_FOR_TESTING};
  process.env.ADMIN_TOKEN='membership-admin-test-token-123456789';
  process.env.ALL_FEATURES_FREE_FOR_TESTING='false';
  t.after(()=>{for(const [key,value] of Object.entries(previous)) if(value===undefined)delete process.env[key];else process.env[key]=value;});
  const {app,store}=await createApp(':memory:');
  t.after(()=>app.close());
  const admin={'x-admin-token':process.env.ADMIN_TOKEN};
  const registration=await app.inject({method:'POST',url:'/api/v1/auth/register',payload:{username:'member_admin_user',password:'membership-test-password'}});
  const user=registration.json().user, token=registration.json().token;
  const publicHeaders={authorization:`Bearer ${token}`};
  assert.equal((await app.inject({url:'/api/v1/admin/membership/users',headers:{'x-admin-token':'incorrect'}})).statusCode,401);
  const catalog=(await app.inject({url:'/api/v1/admin/membership/catalog',headers:admin})).json();
  catalog.versions.push({id:'family',title:'家庭会员',enabled:true,sortOrder:1,description:'家庭共享',benefitIds:['automatic','cloud','books','statistics']});
  catalog.plans.push({...catalog.plans[0],id:'family-monthly',versionId:'family',title:'家庭月卡',rightOverrides:[{benefitId:'cloud',enabled:false,value:''}]});
  catalog.plans[0].enabled=false;
  const save=await app.inject({method:'PUT',url:'/api/v1/admin/membership/catalog',headers:admin,payload:catalog});
  assert.equal(save.statusCode,200,save.body);
  assert.equal((await app.inject({method:'POST',url:'/api/v1/membership/orders',headers:publicHeaders,payload:{productId:'monthly',channel:'wechat',idempotencyKey:'disabled-plan-order'}})).statusCode,404);
  const adjustment=await app.inject({method:'PUT',url:`/api/v1/admin/membership/users/${user.id}`,headers:admin,payload:{productId:'family-monthly',durationDays:10,reason:'客服补偿'}});
  assert.equal(adjustment.statusCode,200,adjustment.body);
  assert.equal(adjustment.json().membership.plan,'family');
  assert.equal(adjustment.json().subscription.provider,'admin');
  assert.equal(adjustment.json().subscription.expiresAt-adjustment.json().subscription.startedAt,10*86400);
  assert.equal(hasMembershipEntitlement(store,user.id,'cloudSync'),false);
  assert.equal(hasMembershipEntitlement(store,user.id,'automaticBookkeeping'),true);
  const current=(await app.inject({url:'/api/v1/membership/current',headers:publicHeaders})).json();
  assert.equal(current.featurePolicies.ledger_sync.enabled,false);
  assert.ok(current.entitlements.some((e:{key:string})=>e.key==='familyBook'));
  process.env.ALL_FEATURES_FREE_FOR_TESTING='true';
  const testing=(await app.inject({url:'/api/v1/membership/current',headers:publicHeaders})).json();
  assert.equal(testing.membership.plan,'family','免费测试仍保留真实会员身份');
  assert.equal(testing.subscription.provider,'admin');
  assert.ok(testing.entitlements.some((e:{key:string;source:string})=>e.key==='cloudSync'&&e.source==='testing_free_access'));
  process.env.ALL_FEATURES_FREE_FOR_TESTING='false';
  const expiredAt=current.subscription.expiresAt;
  const clock=store.now.bind(store);store.now=()=>expiredAt;
  assert.equal((await app.inject({url:'/api/v1/membership/current',headers:publicHeaders})).json().membership.status,'expired');
  assert.equal(hasMembershipEntitlement(store,user.id,'automaticBookkeeping'),false);
  process.env.ALL_FEATURES_FREE_FOR_TESTING='true';
  assert.equal((await app.inject({url:'/api/v1/membership/current',headers:publicHeaders})).json().membership.status,'expired');
  process.env.ALL_FEATURES_FREE_FOR_TESTING='false';
  store.now=clock;
  assert.equal((await app.inject({method:'PUT',url:`/api/v1/admin/membership/users/${user.id}`,headers:admin,payload:{productId:null,durationDays:0,reason:''}})).statusCode,400);
  const cancel=await app.inject({method:'PUT',url:`/api/v1/admin/membership/users/${user.id}`,headers:admin,payload:{productId:null,durationDays:0,reason:'人工取消'}});
  assert.equal(cancel.json().membership.plan,'free');
  assert.equal(hasMembershipEntitlement(store,user.id,'automaticBookkeeping'),false);
  const history=(await app.inject({url:`/api/v1/admin/membership/users/${user.id}/history`,headers:admin})).json();
  assert.equal(history.adjustments.length,2);
  assert.match(history.adjustments[0].details,/人工取消/);
  const users=(await app.inject({url:'/api/v1/admin/membership/users?q=member_admin',headers:admin})).json().users;
  assert.equal(users.length,1);assert.equal(users[0].membership.plan,'free');
  catalog.plans[0].originalPriceInCents=1;
  assert.equal((await app.inject({method:'PUT',url:'/api/v1/admin/membership/catalog',headers:admin,payload:catalog})).statusCode,400);
  assert.equal((await app.inject({url:'/api/v1/membership/catalog'})).json().plans[0].originalPriceInCents,0);
  assert.ok(catalogSchema.safeParse({...catalogSchema.parse(save.json()),plans:[]}).success,'允许全部套餐下架');
});

test('会员订单保存套餐快照，后续编辑与下架不改变已下单的购买信息',async t=>{
  const names=['ALIPAY_APP_ID','ALIPAY_PRIVATE_KEY','ALIPAY_PUBLIC_KEY','ALIPAY_NOTIFY_URL','ALL_FEATURES_FREE_FOR_TESTING'];
  const previous=Object.fromEntries(names.map(n=>[n,process.env[n]]));
  const {privateKey,publicKey}=generateKeyPairSync('rsa',{modulusLength:2048});
  process.env.ALIPAY_APP_ID='2026000000000001';
  process.env.ALIPAY_PRIVATE_KEY=privateKey.export({type:'pkcs8',format:'pem'}).toString();
  process.env.ALIPAY_PUBLIC_KEY=publicKey.export({type:'spki',format:'pem'}).toString();
  process.env.ALIPAY_NOTIFY_URL='https://example.test/alipay';
  process.env.ALL_FEATURES_FREE_FOR_TESTING='false';
  t.after(()=>{for(const [n,v] of Object.entries(previous)) if(v===undefined)delete process.env[n];else process.env[n]=v;});
  const {app,store}=await createApp(':memory:');t.after(()=>app.close());
  store.now=()=>Math.floor(Date.UTC(2027,0,31)/1000);
  const r=(await app.inject({method:'POST',url:'/api/v1/auth/register',payload:{username:'snapshot_member',password:'membership-test-password'}})).json();
  const created=await app.inject({method:'POST',url:'/api/v1/membership/orders',headers:{authorization:`Bearer ${r.token}`},payload:{productId:'quarterly',channel:'alipay',idempotencyKey:'snapshot-member-order'}});
  assert.equal(created.statusCode,200,created.body);
  const order=store.db.prepare('SELECT * FROM membership_orders WHERE user_id=?').get(r.user.id) as {id:string;product_json:string;amount_in_cents:number};
  assert.ok(order);assert.equal(JSON.parse(order.product_json).months,3);assert.equal(order.amount_in_cents,2200);
  const catalog=(await app.inject({url:'/api/v1/membership/catalog'})).json();catalog.plans=[];
  store.db.prepare('UPDATE membership_catalog SET data_json=? WHERE id=1').run(JSON.stringify(catalog));
  const history=(await app.inject({url:'/api/v1/membership/orders',headers:{authorization:`Bearer ${r.token}`}})).json();
  assert.equal(history.orders[0].productTitle,'季度会员');assert.equal(history.orders[0].amountInCents,2200);
  const body:Record<string,string>={app_id:process.env.ALIPAY_APP_ID,out_trade_no:order.id,trade_no:'snapshot-alipay-trade',trade_status:'TRADE_SUCCESS',total_amount:'22.00'};
  const content=Object.keys(body).sort().map(k=>`${k}=${body[k]}`).join('&');
  body.sign=createSign('RSA-SHA256').update(content).sign(privateKey,'base64');
  const callback=()=>app.inject({method:'POST',url:'/api/v1/payments/alipay/notify',payload:body});
  assert.equal((await callback()).statusCode,200);
  const current=()=>app.inject({url:'/api/v1/membership/current',headers:{authorization:`Bearer ${r.token}`}});
  const expiresAt=(await current()).json().subscription.expiresAt;
  assert.equal(expiresAt,Math.floor(Date.UTC(2027,3,30)/1000),'按下单时的三个月时长发放，正确处理月末');
  assert.equal((await callback()).statusCode,200);
  assert.equal((await current()).json().subscription.expiresAt,expiresAt,'重复回调不重复发放');
});
