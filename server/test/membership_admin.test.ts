  // 模拟已通过 Apple 验签并持久化的交易；此处验证会员查询，不替代验签测试。
  store.db.prepare('INSERT INTO apple_transactions VALUES(?,?,?,?,?,?,?,?,?,?)').run('apple-state','apple-state',r.user.id,'haohaojizhang.membership.monthly','Sandbox',now,expiresAt,null,'verified-fixture',now);
  const current=async()=>(await app.inject({url:'/api/v1/membership/current',headers:{authorization:`Bearer ${r.token}`}})).json();
  assert.equal((await current()).membership.status,'active');
  const catalog=(await app.inject({url:'/api/v1/membership/catalog'})).json();catalog.plans=[];
  store.db.prepare('UPDATE membership_catalog SET data_json=? WHERE id=1').run(JSON.stringify(catalog));
  assert.ok((await current()).entitlements.some((e:{key:string})=>e.key==='cloudSync'));
  store.now=()=>expiresAt;
  const expired=await current();
  assert.equal(expired.membership.plan,'pro');assert.equal(expired.membership.status,'expired');
  assert.equal(expired.entitlements.length,0);
  process.env.ALL_FEATURES_FREE_FOR_TESTING='true';
